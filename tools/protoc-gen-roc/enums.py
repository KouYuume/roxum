"""Open enum validation and nominal numeric codecs."""
import re
from google.protobuf import descriptor_pb2 as d
from schema import require


def validate(symbol, keywords):
    enum = symbol.descriptor
    loc = symbol.location
    options = d.EnumOptions()
    options.CopyFrom(enum.options)
    options.ClearField('allow_alias')
    require(not options.SerializeToString(), loc, 'unsupported enum options')
    require(enum.value and enum.value[0].number == 0, loc, 'first enum value must be zero')
    names, numbers = set(), set()
    reserved = keywords | {'is_eq', 'from_number', 'to_number', 'read_int32', 'write_int32', 'read_packed_int32'}
    for value in enum.value:
        where = loc + '.' + value.name
        require(re.fullmatch(r'[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*', value.name), where, 'enum values must use uppercase snake case')
        name = value.name.lower()
        require(name not in names and name not in reserved, where, 'enum value name collision')
        require(not value.options.SerializeToString(), where, 'enum value options are not supported')
        require(value.number not in numbers or enum.options.allow_alias, where, 'duplicate number requires allow_alias')
        names.add(name)
        numbers.add(value.number)


def emit(symbol):
    name = symbol.roc_name
    lines = ['# Generated by protoc-gen-roc; regenerate from the schema.',
             f'# Protobuf enum: {symbol.full_name}', 'import wire.ProtobufWire',
             'import wire.ProtobufScalar', '', f'{name} := I32.{{', '\tis_eq : _']
    for value in symbol.descriptor.value:
        lines += [f'\t{value.name.lower()} : {name}', f'\t{value.name.lower()} = {name}.({value.number})']
    lines += [f'\tfrom_number : I32 -> {name}', f'\tfrom_number = |number| {name}.(number)',
              f'\tto_number : {name} -> I32', f'\tto_number = |{name}.(number)| number',
              f'\tread_int32 : ProtobufWire.Reader -> Try(({name}, ProtobufWire.Reader), ProtobufWire.Error)',
              '\tread_int32 = |reader| {', '\t\t(number, after) = ProtobufScalar.read_int32(reader)?',
              f'\t\tOk(({name}.from_number(number), after))', '\t}',
              f'\twrite_int32 : ProtobufWire.Writer, {name} -> Try(ProtobufWire.Writer, ProtobufWire.Error)',
              f'\twrite_int32 = |writer, value| ProtobufScalar.write_int32(writer, {name}.to_number(value))',
              f'\tread_packed_int32 : ProtobufWire.Reader -> Try((List({name}), ProtobufWire.Reader), ProtobufWire.Error)',
              '\tread_packed_int32 = |reader| {', '\t\t(numbers, after) = ProtobufScalar.read_packed_int32(reader)?',
              f'\t\tOk((numbers.map({name}.from_number), after))', '\t}', '}', '']
    return '\n'.join(lines)
