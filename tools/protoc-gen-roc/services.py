"""Opt-in Unary and streaming bindings; codec-only generation remains platform-free."""
import re
import recursion


def emit(request, messages, identities, require):
    paths, _ = recursion.layout(messages, identities)
    files = {f.name: f for f in request.proto_file}
    runtime_names = {'main', 'handlers', 'grpcunary', 'grpctimeout', 'grpcmetadata', 'router', 'methodrouter', 'protobufwire'}
    runtimes = {(False, False): 'GrpcUnary', (False, True): 'GrpcServerStream',
                (True, False): 'GrpcClientStream', (True, True): 'GrpcDuplex'}
    service_runtimes = {runtimes[method.client_streaming, method.server_streaming]
                        for name in request.file_to_generate for service in files[name].service for method in service.method}
    runtime_names.update(runtime.lower() for runtime in service_runtimes)
    if service_runtimes - {'GrpcUnary'}:
        runtime_names.add('grpcserverstream')  # Shared streaming limits.
    used = {p.split('.')[0].lower() for p in paths.values()}
    require(not used & runtime_names, 'services', 'message module conflicts with a service binding import')
    used |= runtime_names
    output = []
    for filename in sorted(request.file_to_generate):
        file = files[filename]
        visible = {filename, *file.dependency}
        pending = list(file.dependency)
        while pending:
            dependency = files[pending.pop()]
            for index in dependency.public_dependency:
                name = dependency.dependency[index]
                if name not in visible:
                    visible.add(name)
                    pending.append(name)
        for service in file.service:
            location = filename + ':' + service.name
            require(re.fullmatch(r'[A-Z][A-Za-z0-9]*', service.name), location, 'unsupported service name')
            module = service.name + 'Service'
            require(module.lower() not in used, location, 'service module collision')
            used.add(module.lower())
            require(not service.options.SerializeToString(), location, 'service options are unsupported')
            require(service.method, location, 'empty service')
            imports, methods = set(), []
            method_names, handler_fields = set(), set()
            for method in service.method:
                loc = location + '.' + method.name
                require(re.fullmatch(r'[A-Z][A-Za-z0-9]*', method.name), loc, 'unsupported method name')
                runtime = runtimes[method.client_streaming, method.server_streaming]
                field = 'duplex_' + method.name.lower() if runtime == 'GrpcDuplex' else 'call_' + method.name.lower() + '!'
                require(method.name not in method_names and field not in handler_fields, loc, 'method binding name collision')
                method_names.add(method.name)
                handler_fields.add(field)
                require(not method.options.SerializeToString(), loc, 'method options are unsupported')
                types = []
                for name in (method.input_type, method.output_type):
                    symbol = identities.get(name)
                    require(symbol is not None and not symbol.is_enum and not symbol.descriptor.options.map_entry, loc, 'RPC type must be a message')
                    require(symbol.file_name in visible, loc, 'RPC type is not visible through imports')
                    types.append(paths[name])
                    imports.add(paths[name].split('.')[0])
                path = '/' + '.'.join(filter(None, (file.package, service.name))) + '/' + method.name
                methods.append((field, path, *types, runtime))
            lines = ['# Generated by protoc-gen-roc; regenerate from the schema.', 'import pf.Router', 'import pf.MethodRouter', 'import grpc.GrpcUnary', 'import grpc.GrpcTimeout', 'import grpc.GrpcMetadata', 'import wire.ProtobufWire']
            streaming = any(m[4] != "GrpcUnary" for m in methods)
            unary = any(m[4] == "GrpcUnary" for m in methods)
            if streaming:
                lines.append('import grpc.GrpcServerStream')
            if any(m[4] == 'GrpcClientStream' for m in methods):
                lines.append('import grpc.GrpcClientStream')
            duplex_states = {field: 'state_' + field.removeprefix('duplex_')
                             for field, _, _, _, runtime in methods if runtime == 'GrpcDuplex'}
            if duplex_states:
                lines.append('import grpc.GrpcDuplex')
            handler_type = 'Handlers(' + ', '.join(['model', *duplex_states.values()]) + ')'
            limits_type = '{ unary : GrpcUnary.Limits, streaming : GrpcServerStream.Limits }' if streaming and unary else ('GrpcServerStream.Limits' if streaming else 'GrpcUnary.Limits')
            lines += ['import ' + name for name in sorted(imports)]
            lines += ['', module + ' := [].{', f'\t{handler_type} : {{']
            for field, _, input_type, output_type, runtime in methods:
                if runtime == "GrpcDuplex":
                    signature = f'GrpcDuplex.Callbacks(model, {duplex_states[field]}, {input_type}, {output_type})'
                elif runtime == "GrpcClientStream":
                    signature = f'model, List(GrpcMetadata.Entry) => Try(GrpcClientStream.Consumer({input_type}, {output_type}), GrpcUnary.Failure)'
                else:
                    signature = f'model, {input_type}, List(GrpcMetadata.Entry) => Try({runtime}.Response({output_type}), GrpcUnary.Failure)'
                lines.append(f'\t\t{field} : {signature},')
            lines += ['\t}', f'\tregister : Router(model, tag, provided), {module}.{handler_type}, {limits_type}, ProtobufWire.Limits -> Router(model, tag, provided)', '\tregister = |router, handlers, limits, codec_limits| {', '\t\tvar $router = router']
            for field, path, input_type, output_type, runtime in methods:
                is_stream = runtime != "GrpcUnary"
                selected = ("limits.streaming" if is_stream else "limits.unary") if streaming and unary else "limits"
                timeout = f"GrpcTimeout.streaming_layer({selected})" if is_stream else f"GrpcTimeout.layer({selected}.metadata)"
                lines += [f'\t\t$router = $router.route("{path}", MethodRouter.post({runtime}.handler(|bytes| {input_type}.decode(bytes, codec_limits), {output_type}.encode, handlers.{field}, {selected})).layer({timeout}))']
            lines += ['\t\t$router', '\t}', '}', '']
            output.append((module, '\n'.join(lines)))
    return output
