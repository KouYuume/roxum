"""Opt-in finite Unary bindings; codec-only generation remains platform-free."""
import re
import recursion


def emit(request, messages, identities, require):
    paths, _ = recursion.layout(messages, identities)
    files = {f.name: f for f in request.proto_file}
    runtime_names = {'main', 'handlers', 'grpcunary', 'grpctimeout', 'grpcmetadata', 'router', 'methodrouter', 'protobufwire'}
    used = {p.split('.')[0].lower() for p in paths.values()}
    require(not used & runtime_names, 'services', 'message module conflicts with a service binding import')
    used |= runtime_names
    output = []
    for filename in sorted(request.file_to_generate):
        file = files[filename]
        visible = {filename, *file.dependency}
        pending = list(file.dependency)
        while pending:
            dependency = files[pending.pop()]
            for index in dependency.public_dependency:
                name = dependency.dependency[index]
                if name not in visible:
                    visible.add(name)
                    pending.append(name)
        for service in file.service:
            location = filename + ':' + service.name
            require(re.fullmatch(r'[A-Z][A-Za-z0-9]*', service.name), location, 'unsupported service name')
            module = service.name + 'Service'
            require(module.lower() not in used, location, 'service module collision')
            used.add(module.lower())
            require(not service.options.SerializeToString(), location, 'service options are unsupported')
            require(service.method, location, 'empty service')
            imports, methods, seen = set(), [], set()
            for method in service.method:
                loc = location + '.' + method.name
                require(re.fullmatch(r'[A-Z][A-Za-z0-9]*', method.name), loc, 'unsupported method name')
                field = 'call_' + method.name.lower() + '!'
                require(field not in seen, loc, 'method binding name collision')
                seen.add(field)
                require(not method.client_streaming and not method.server_streaming, loc, 'only Unary RPC is supported')
                require(not method.options.SerializeToString(), loc, 'method options are unsupported')
                types = []
                for name in (method.input_type, method.output_type):
                    symbol = identities.get(name)
                    require(symbol is not None and not symbol.is_enum and not symbol.descriptor.options.map_entry, loc, 'RPC type must be a message')
                    require(symbol.file_name in visible, loc, 'RPC type is not visible through imports')
                    types.append(paths[name])
                    imports.add(paths[name].split('.')[0])
                path = '/' + '.'.join(filter(None, (file.package, service.name))) + '/' + method.name
                methods.append((field, path, *types))
            lines = ['# Generated by protoc-gen-roc; regenerate from the schema.', 'import pf.Router', 'import pf.MethodRouter', 'import grpc.GrpcUnary', 'import grpc.GrpcTimeout', 'import grpc.GrpcMetadata', 'import wire.ProtobufWire']
            lines += ['import ' + name for name in sorted(imports)]
            lines += ['', module + ' := [].{', '\tHandlers(model) : {']
            lines += [f'\t\t{field} : model, {input_type}, List(GrpcMetadata.Entry) => Try(GrpcUnary.Response({output_type}), GrpcUnary.Failure),' for field, _, input_type, output_type in methods]
            lines += ['\t}', f'\tregister : Router(model, tag, provided), {module}.Handlers(model), GrpcUnary.Limits, ProtobufWire.Limits -> Router(model, tag, provided)', '\tregister = |router, handlers, limits, codec_limits| {', '\t\tvar $router = router']
            for field, path, input_type, output_type in methods:
                lines += [f'\t\t$router = $router.route("{path}", MethodRouter.post(GrpcUnary.handler(|bytes| {input_type}.decode(bytes, codec_limits), {output_type}.encode, handlers.{field}, limits)).layer(GrpcTimeout.layer(limits.metadata)))']
            lines += ['\t\t$router', '\t}', '}', '']
            output.append((module, '\n'.join(lines)))
    return output
