"""Generate Roc service bindings and an independent Python client from service.proto."""
import argparse
import os
from pathlib import Path
import subprocess
import sys
import tempfile

EXAMPLE = Path(__file__).resolve().parent
ROOT = (EXAMPLE / '../../..').resolve()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tool-root', type=Path, default=ROOT)
    parser.add_argument('--wire', default='../../../../libraries/roc-protobuf/package/main.roc')
    parser.add_argument('--grpc', default='../../package/main.roc')
    parser.add_argument('--platform', default='../../../../platform/main.roc')
    parser.add_argument('--python-output', type=Path, default=ROOT / 'zig-out/grpc-example')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    tools = args.tool_root.resolve()
    args.python_output.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as directory:
        output = Path(directory)
        subprocess.run([str(tools / 'zig-out/protobuf-codegen/bin/protoc'), '-I', str(EXAMPLE),
                        '--plugin=protoc-gen-roc=' + str(tools / 'tools/protoc-gen-roc/protoc-gen-roc'),
                        f'--roc_opt=wire={args.wire},grpc={args.grpc},pf={args.platform}', '--roc_out=' + directory,
                        str(EXAMPLE / 'service.proto')], check=True)
        files = sorted(output.glob('*.roc'))
        subprocess.run([os.environ.get('ROC_BIN', 'roc'), 'fmt', *map(str, files)], check=True)
        generated = EXAMPLE / 'generated'
        if args.check:
            assert {p.name for p in files} == {p.name for p in generated.glob('*.roc')}
            for file in files:
                assert file.read_bytes() == (generated / file.name).read_bytes(), file.name + ': regenerate example'
        else:
            generated.mkdir(exist_ok=True)
            names = {file.name for file in files}
            # Only remove obsolete generator-owned modules, after generation succeeds.
            for old in generated.glob('*.roc'):
                if old.name not in names and old.read_bytes().startswith(b'# Generated by protoc-gen-roc;'):
                    old.unlink()
            for file in files:
                (generated / file.name).write_bytes(file.read_bytes())
    subprocess.run([sys.executable, '-m', 'grpc_tools.protoc', '-I', str(EXAMPLE),
                    '--python_out=' + str(args.python_output), '--grpc_python_out=' + str(args.python_output),
                    str(EXAMPLE / 'service.proto')], check=True)


if __name__ == '__main__':
    main()
